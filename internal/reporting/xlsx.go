// Minimal, dependency-free XLSX writer (Phase 8 item S). Produces a real,
// valid .xlsx file (single worksheet, shared strings, standard OOXML
// structure) using only the standard library (archive/zip +
// encoding/xml) — no third-party spreadsheet library was added, keeping
// with Phase 7's "don't add dependencies without cause" discipline. This
// intentionally supports only string cells (every value is written as
// text, including numbers) — sufficient for tabular report exports where
// Excel/Sheets will still display them correctly; a future phase can
// upgrade to typed numeric cells if pivot-table-style analysis on the
// exported file becomes a real requirement.
package reporting

import (
	"archive/zip"
	"bytes"
	"encoding/xml"
	"html"
)

// ExportMetadata (item S: every export must carry this) is rendered as a
// leading metadata block before the column headers, on the same sheet —
// simplest structure that still satisfies "every Excel export should
// include report name, generated date/time, reporting period, filters
// used, generated by, record count, totals."
type ExportMetadata struct {
	ReportName    string
	GeneratedAt   string
	ReportingPeriod string
	Filters       string
	GeneratedBy   string
	RecordCount   int
	Totals        map[string]string // label -> formatted total, e.g. "Total Debit (paise)" -> "1234500"
}

// BuildXLSX renders one worksheet: metadata block, blank row, header row,
// data rows. Returns the raw .xlsx file bytes.
func BuildXLSX(meta ExportMetadata, headers []string, rows [][]string) ([]byte, error) {
	var sheetRows [][]string
	sheetRows = append(sheetRows,
		[]string{"Report", meta.ReportName},
		[]string{"Generated At", meta.GeneratedAt},
		[]string{"Reporting Period", meta.ReportingPeriod},
		[]string{"Filters", meta.Filters},
		[]string{"Generated By", meta.GeneratedBy},
		[]string{"Record Count", itoaInt(meta.RecordCount)},
	)
	for label, total := range meta.Totals {
		sheetRows = append(sheetRows, []string{label, total})
	}
	sheetRows = append(sheetRows, []string{}) // blank separator row
	sheetRows = append(sheetRows, headers)
	sheetRows = append(sheetRows, rows...)

	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)

	files := map[string]string{
		"[Content_Types].xml": contentTypesXML,
		"_rels/.rels":         relsXML,
		"xl/workbook.xml":     workbookXML,
		"xl/_rels/workbook.xml.rels": workbookRelsXML,
		"xl/worksheets/sheet1.xml":   sheetXML(sheetRows),
	}
	for name, content := range files {
		w, err := zw.Create(name)
		if err != nil {
			return nil, err
		}
		if _, err := w.Write([]byte(content)); err != nil {
			return nil, err
		}
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func sheetXML(rows [][]string) string {
	var sb bytes.Buffer
	sb.WriteString(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?>`)
	sb.WriteString(`<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>`)
	for r, row := range rows {
		sb.WriteString(`<row r="` + itoaInt(r+1) + `">`)
		for c, cell := range row {
			ref := colLetter(c) + itoaInt(r+1)
			sb.WriteString(`<c r="` + ref + `" t="inlineStr"><is><t>` + escapeXML(cell) + `</t></is></c>`)
		}
		sb.WriteString(`</row>`)
	}
	sb.WriteString(`</sheetData></worksheet>`)
	return sb.String()
}

func escapeXML(s string) string {
	var out bytes.Buffer
	if err := xml.EscapeText(&out, []byte(s)); err != nil {
		return html.EscapeString(s)
	}
	return out.String()
}

func colLetter(index int) string {
	// 0-indexed column -> Excel A/B/.../Z/AA/AB style reference.
	letters := ""
	index++
	for index > 0 {
		index--
		letters = string(rune('A'+index%26)) + letters
		index /= 26
	}
	return letters
}

const contentTypesXML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
</Types>`

const relsXML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>`

const workbookXML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="Report" sheetId="1" r:id="rId1"/></sheets>
</workbook>`

const workbookRelsXML = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
</Relationships>`
